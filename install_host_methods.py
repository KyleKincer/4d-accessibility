#!/usr/bin/env python3
"""Install portable bridge host methods into a 4D source project, without binaries."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parent
MARKER = "// Generated by AccessibilityBridge/install_host_methods.py; body SHA256: "
BEGIN = "// Accessibility bridge host declarations begin"
END = "// Accessibility bridge host declarations end"
AREA_METHODS = {"AXB_ALPNode", "AXB_ALPRows", "AXB_ALPRowsSelect", "AXB_ALPSelect",
                "AXB_ALPGrid", "AXB_ALPGridAction", "AXB_ALPGridConfirm", "AXB_ALPGridValue", "AXB_ALPEditor"}
AREA_NAME = "__AXB_Bridge"
AREA_KIND = "%AXB Area"
AREA = {"type": "plugin", "pluginAreaKind": AREA_KIND, "dataSource": "",
        "left": 0, "top": 0, "width": 1, "height": 1, "enterable": False,
        "focusable": False, "printable": False}
METADATA_NAME = "AXB.FormMetadata.json"
METADATA_OWNER = "AccessibilityBridge/install_host_methods.py"
# A form object's own accessibility metadata, kept in its definition beside 4D's
# properties under this key. 4D ignores the key and its Form Editor preserves it.
CONTROL_KEY = "axb"
# The static parts of the `controls` option that a definition may hold, with
# their types. Formulas and other runtime values stay in AXB_Configure.
CONTROL_TEXT = {"label": 512, "description": 512, "automationKey": 256}
CONTROL_FLAGS = ("protected", "decorative", "multiline")
# The static form-level options a form's own "axb" may hold.
FORM_TEXT = {"label": 512, "automationKey": 128}
FORM_FLAGS = ("omitOutsideWindow", "enabled")
GRID_KINDS = ("array", "outline", "areaList", "collection", "entity", "selection", "listSubform", "hierarchicalList")


def metadata_digest(forms, controls=None, options=None, grids=None):
    # Without definition metadata the digest covers the forms alone, as before, so a
    # resource generated by an earlier installer still verifies; sections a form
    # definition does not use stay out of the digest too.
    extra = {key: value for key, value in (("controls", controls), ("options", options), ("grids", grids)) if value}
    value = forms if not extra else {**extra, "forms": forms}
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(",", ":")).encode()).hexdigest()


def text_value(item, limit):
    return isinstance(item, str) and bool(item.strip()) and len(item) <= limit


def form_options(value, where):
    """Validate a form's own "axb": the static form-level options."""
    if not isinstance(value, dict) or not value:
        raise ValueError(f"{where}: form \"{CONTROL_KEY}\" must be a non-empty object")
    for key, item in value.items():
        if key in FORM_TEXT:
            if not text_value(item, FORM_TEXT[key]):
                raise ValueError(f"{where}: form {CONTROL_KEY}.{key} must be non-empty text of at most {FORM_TEXT[key]} characters")
        elif key in FORM_FLAGS:
            if not isinstance(item, bool):
                raise ValueError(f"{where}: form {CONTROL_KEY}.{key} must be true or false")
        elif key == "idleRefresh":
            if type(item) not in (int, float) or not 1 <= item <= 60:
                raise ValueError(f"{where}: form {CONTROL_KEY}.idleRefresh must be a number of seconds from 1 to 60")
        else:
            allowed = sorted([*FORM_TEXT, *FORM_FLAGS, "idleRefresh"])
            raise ValueError(f"{where}: unknown form {CONTROL_KEY}.{key}; use one of {', '.join(allowed)}, "
                             "or put runtime values in AXB_Configure")
    return value


def column_metadata(value, where):
    if not isinstance(value, dict) or not value:
        raise ValueError(f"{where}: column metadata must be a non-empty object")
    for key, item in value.items():
        if key in ("label", "automationKey"):
            limit = 512 if key == "label" else 256
            if not text_value(item, limit):
                raise ValueError(f"{where}: {key} must be non-empty text of at most {limit} characters")
        elif key == "decorative":
            if not isinstance(item, bool):
                raise ValueError(f"{where}: decorative must be true or false")
        else:
            raise ValueError(f"{where}: unknown column key {key}; use label, automationKey or decorative, "
                             "or put a value formula in AXB_Configure")
    return value


def grid_metadata(value, where):
    """Validate the static part of a grid's options, kept on its list box or area."""
    if not isinstance(value, dict) or not value:
        raise ValueError(f"{where}: {CONTROL_KEY}.grid must be a non-empty object")
    for key, item in value.items():
        if key == "kind":
            if item not in GRID_KINDS:
                raise ValueError(f"{where}: {CONTROL_KEY}.grid.kind must be one of {', '.join(GRID_KINDS)}")
        elif key == "label":
            if not text_value(item, 512):
                raise ValueError(f"{where}: {CONTROL_KEY}.grid.label must be non-empty text of at most 512 characters")
        elif key == "keyProperty":
            if not text_value(item, 255):
                raise ValueError(f"{where}: {CONTROL_KEY}.grid.keyProperty must be non-empty text")
        elif key == "keyColumn":
            if not (text_value(item, 255) or (type(item) is int and item >= 1)):
                raise ValueError(f"{where}: {CONTROL_KEY}.grid.keyColumn must be a column name, or an AreaList column number")
        elif key == "columns":
            if not isinstance(item, dict) or not item:
                raise ValueError(f"{where}: {CONTROL_KEY}.grid.columns must be a non-empty object")
            for column, metadata in item.items():
                if not column or len(column) > 255:
                    raise ValueError(f"{where}: {CONTROL_KEY}.grid.columns has an invalid column name")
                column_metadata(metadata, f"{where}: {CONTROL_KEY}.grid.columns.{column}")
        else:
            raise ValueError(f"{where}: unknown {CONTROL_KEY}.grid.{key}; use one of columns, keyColumn, keyProperty, kind, label, "
                             "or put formulas and pointers (ready, onSelection, selection, meta, keys) in AXB_Configure")
    kind = value.get("kind")
    if kind in ("array", "outline") and isinstance(value.get("keyColumn"), int):
        raise ValueError(f"{where}: {CONTROL_KEY}.grid.keyColumn names a column for an {kind} grid")
    if kind == "areaList" and isinstance(value.get("keyColumn"), str):
        raise ValueError(f"{where}: {CONTROL_KEY}.grid.keyColumn is a column number for an AreaList grid")
    return value


def control_metadata(value, where):
    """Validate one object's definition metadata, as AXB_ViewCreate would at run time."""
    if not isinstance(value, dict) or not value:
        raise ValueError(f"{where}: \"{CONTROL_KEY}\" must be a non-empty object")
    for key, item in value.items():
        if key == "grid":
            grid_metadata(item, where)
        elif key in CONTROL_TEXT:
            if not isinstance(item, str) or not item.strip() or len(item) > CONTROL_TEXT[key]:
                raise ValueError(f"{where}: {CONTROL_KEY}.{key} must be non-empty text of at most {CONTROL_TEXT[key]} characters")
        elif key in CONTROL_FLAGS:
            if not isinstance(item, bool):
                raise ValueError(f"{where}: {CONTROL_KEY}.{key} must be true or false")
        elif key == "layer":
            if type(item) is not int or abs(item) > 32767:
                raise ValueError(f"{where}: {CONTROL_KEY}.layer must be an integer from -32767 to 32767")
        elif key == "step":
            if type(item) not in (int, float) or item <= 0:
                raise ValueError(f"{where}: {CONTROL_KEY}.step must be a positive number")
        elif key == "cells":
            if (not isinstance(item, list) or not 1 <= len(item) <= 256 or
                    any(not isinstance(cell, str) or not cell or len(cell) > 512 for cell in item)):
                raise ValueError(f"{where}: {CONTROL_KEY}.cells must list 1 to 256 non-empty labels")
        else:
            allowed = sorted([*CONTROL_TEXT, *CONTROL_FLAGS, "layer", "step", "cells", "grid"])
            raise ValueError(f"{where}: unknown {CONTROL_KEY}.{key}; use one of {', '.join(allowed)}, "
                             "or put runtime values in AXB_Configure")
    return value


def duplicate_warnings(form, controls):
    """Copying an object in the Form Editor copies its metadata: report repeated names."""
    warnings = []
    for key in ("label", "automationKey"):
        seen = {}
        for name in sorted(controls):
            value = controls[name].get(key)
            if value is not None:
                seen.setdefault(value, []).append(name)
        warnings += [f"{form}: objects {', '.join(names)} share {CONTROL_KEY}.{key} \"{value}\"; "
                     "a copied object keeps its original's metadata"
                     for value, names in seen.items() if len(names) > 1]
    return warnings


def form_metadata_changes(project, enabled, warnings=None):
    """Package list-row markers and objects' "axb" metadata, which 4D cannot query
    from compiled project forms.

    Source refreshes also refresh an existing generated resource. Ordinary
    method-only installs without that resource never inspect application forms.
    """
    target = project.parent / "Resources" / METADATA_NAME
    if not enabled and not target.exists():
        return {}
    if target.exists():
        old = json.loads(target.read_text())
        if (old.get("generatedBy") != METADATA_OWNER or old.get("schema") != 1 or
                old.get("sha256") != metadata_digest(old.get("forms"), old.get("controls"), old.get("options"), old.get("grids"))):
            raise ValueError("Refusing to replace non-generated or edited form metadata: " + str(target))
    paths = sorted((project / "Sources/Forms").glob("*/form.4DForm"))
    paths += sorted((project / "Sources/TableForms").glob("*/*/form.4DForm"))
    definitions = {str(p.parent.relative_to(project / "Sources")): json.loads(p.read_text()) for p in paths}
    table_names = {}
    catalog = project / "Sources/catalog.4DCatalog"
    if catalog.is_file():
        table_names = {t.get("name"): t.get("id") for t in ET.parse(catalog).iter("table")}

    def metadata(key, chain):
        if key in chain or key not in definitions:
            return {}  # Unknown layout remains unavailable at runtime.
        form = definitions[key]
        inherited = form.get("inheritedForm")
        result = {}
        if isinstance(inherited, str) and inherited.strip() and "/" not in inherited and "\\" not in inherited:
            table = form.get("inheritedFormTable")
            parent = "Forms/" + inherited
            if table not in (None, "", " ", 0):
                parent = "TableForms/" + str(table_names.get(str(table), table)) + "/" + inherited
            result.update(metadata(parent, [*chain, key]))
        result.update({name: form[name] for name in ("markerHeader", "markerBody") if name in form})
        lists = result.get("lists", {}).copy()
        # An inherited object shows in the derived form with its base's metadata.
        controls = result.get("controls", {}).copy()
        grids = result.get("grids", {}).copy()
        for page in form.get("pages", []):
            for name, control in (page or {}).get("objects", {}).items():
                where = f"Sources/{key}: {name}"
                if CONTROL_KEY in control:
                    stored = dict(control_metadata(control[CONTROL_KEY], where))
                    grid = stored.pop("grid", None)
                    if grid is not None:
                        grids[name] = grid
                    if stored:
                        controls[name] = stored
                    else:
                        controls.pop(name, None)
                # A list box column's own "axb" completes that grid's columns.
                columns = {}
                for column in control.get("columns", []) if isinstance(control.get("columns"), list) else []:
                    if isinstance(column, dict) and CONTROL_KEY in column:
                        column_name = column.get("name")
                        if not isinstance(column_name, str) or not column_name:
                            raise ValueError(f"{where}: a column with \"{CONTROL_KEY}\" needs a name")
                        columns[column_name] = column_metadata(column[CONTROL_KEY], f"{where}: column {column_name}")
                if columns:
                    grid = dict(grids.get(name, {}))
                    merged = {column: dict(stored_column) for column, stored_column in grid.get("columns", {}).items()}
                    for column, stored_column in columns.items():
                        if column in merged and set(merged[column]) & set(stored_column):
                            raise ValueError(f"{where}: column {column} is described both on the column and in {CONTROL_KEY}.grid.columns")
                        merged.setdefault(column, {}).update(stored_column)
                    grid["columns"] = merged
                    grids[name] = grid
                if control.get("type") == "subform" and control.get("listForm"):
                    mode = control.get("selectionMode", "none")
                    lists[name] = {"selection": mode if mode in ("none", "single", "multiple") else "none",
                                   "enterable": control.get("enterableInList") is True}
        if lists:
            result["lists"] = lists
        if controls:
            result["controls"] = controls
        else:
            result.pop("controls", None)
        if grids:
            result["grids"] = grids
        return result

    forms = {}
    all_controls = {}
    all_options = {}
    all_grids = {}
    for key in definitions:
        layout = metadata(key, [])
        if key.startswith("TableForms/"):
            _, table, name = key.split("/", 2)
        else:
            table, name = "0", key[len("Forms/"):]
        # A form's own options describe that form; a derived form does not inherit them.
        if CONTROL_KEY in definitions[key]:
            all_options.setdefault(table, {})[name] = form_options(definitions[key][CONTROL_KEY], f"Sources/{key}")
        if layout.get("grids"):
            all_grids.setdefault(table, {})[name] = layout["grids"]
        if layout.get("controls"):
            all_controls.setdefault(table, {})[name] = layout["controls"]
            if warnings is not None:
                warnings += duplicate_warnings("Sources/" + key, layout["controls"])
        header, body = layout.get("markerHeader", 0), layout.get("markerBody")
        item = {}
        if (type(header) is int and type(body) is int and 0 <= header < body <= 32767):
            item.update(header=header, body=body)
        if layout.get("lists"):
            item["lists"] = layout["lists"]
        if not item:
            continue
        forms.setdefault(table, {})[name] = item
    if not forms and not all_controls and not all_options and not all_grids and not target.exists():
        return {}
    content = {"generatedBy": METADATA_OWNER, "schema": 1,
               "sha256": metadata_digest(forms, all_controls, all_options, all_grids), "forms": forms}
    for section, value in (("controls", all_controls), ("options", all_options), ("grids", all_grids)):
        if value:
            content[section] = value
    return {target: json.dumps(content, ensure_ascii=False, sort_keys=True, indent=2) + "\n"}


def lifecycle_areas(form):
    """Find all reserved areas, validating their containing pages first."""
    pages = form.get("pages")
    if not isinstance(pages, list) or not pages:
        raise ValueError("Form must have a pages collection")
    found = []
    for number, page in enumerate(pages):
        if page is None:
            continue
        if not isinstance(page, dict) or not isinstance(page.get("objects", {}), dict):
            raise ValueError("Invalid form page or objects")
        for name, obj in page.get("objects", {}).items():
            if not isinstance(obj, dict):
                raise ValueError("Invalid form object: " + name)
            if name == AREA_NAME or name.startswith(AREA_NAME + ".") or obj.get("pluginAreaKind") == AREA_KIND:
                found.append((number, name, obj))
    return found


def area_form(form, configuration=""):
    """Return a copy with one lifecycle area; never change existing objects."""
    if not isinstance(form, dict):
        raise ValueError("Form must be an object")
    if configuration and not re.fullmatch(r"[A-Za-z][A-Za-z0-9_-]{0,63}", configuration):
        raise ValueError("Invalid area configuration key")
    if form.get("destination") not in (None, "", "detailScreen"):
        raise ValueError("Lifecycle areas require a detail screen or unspecified destination")
    result = json.loads(json.dumps(form))
    area_name = AREA_NAME + ("." + configuration if configuration else "")
    pages = result.get("pages")
    found = lifecycle_areas(result)
    if found:
        if found != [(0, area_name, AREA)]:
            raise ValueError("Existing lifecycle area differs from the installer-owned area")
        return result
    if pages[0] is None:
        pages[0] = {"objects": {}}
    pages[0].setdefault("objects", {})[area_name] = AREA.copy()
    return result


def form_changes(project, names, all_forms):
    """Preflight every selected form before any helper or form is written."""
    if not names and not all_forms:
        # A method-only refresh never reads or parses application forms.
        return {}
    paths = sorted((project / "Sources/Forms").glob("*/form.4DForm"))
    paths += sorted((project / "Sources/TableForms").glob("*/*/form.4DForm"))
    by_name = {str(p.parent.relative_to(project / "Sources")): p for p in paths}
    selected = paths if all_forms else []
    for name in names:
        key = name if name.startswith(("Forms/", "TableForms/")) else "Forms/" + name
        if key not in by_name:
            raise ValueError("Unknown form: " + name)
        selected.append(by_name[key])
    originals = {p: p.read_text() for p in paths}
    forms = {p: json.loads(text) for p, text in originals.items()}
    table_names = {}
    catalog = project / "Sources/catalog.4DCatalog"
    if catalog.is_file():
        for table in ET.parse(catalog).iter("table"):
            if table.get("name") and table.get("id"):
                table_names[table.get("name")] = table.get("id")

    def parent(path):
        form = forms[path]
        inherited = form.get("inheritedForm")
        if inherited in (None, "", " "):
            return None
        if not isinstance(inherited, str) or "/" in inherited or "\\" in inherited:
            raise ValueError("Resolve external/inline inherited forms before adding an area: " + str(path.relative_to(project)))
        table = form.get("inheritedFormTable")
        if table in (None, "", " ", 0):
            key = "Forms/" + inherited
        else:
            number = table_names.get(str(table), str(table))
            key = "TableForms/" + number + "/" + inherited
        if key not in by_name:
            raise ValueError("Unknown inherited form " + key + " in " + str(path.relative_to(project)))
        return by_name[key]

    # Row forms can have an unspecified/detail destination. Their actual use,
    # rather than that property alone, determines lifecycle ownership. Protect
    # their inherited bases too, placing areas in separate detail branches.
    row_forms = set()
    for path, form in forms.items():
        for page in form.get("pages", []):
            for control in (page or {}).get("objects", {}).values():
                row = control.get("listForm")
                if control.get("type") != "subform" or not isinstance(row, str) or not row:
                    continue
                table = control.get("table")
                if table in (None, "", " ", 0) and path.parent.parent.parent.name == "TableForms":
                    table = path.parent.parent.name
                table = table_names.get(str(table), str(table))
                target = by_name.get("TableForms/" + table + "/" + row)
                if target:
                    row_forms.add(target)
    row_bases = set(row_forms)
    for path in row_forms:
        seen = {path}
        try:
            while (path := parent(path)) is not None and path not in seen:
                row_bases.add(path)
                seen.add(path)
        except ValueError:
            pass  # Unselected unresolved row inheritance is not modified.

    # Older bulk installers could instrument an unspecified row destination or
    # a shared base. Move only our exact area, with all detail branches selected
    # so removing inherited ownership cannot silently retire another window.
    migrated = set()
    for path in sorted(row_bases):
        found = lifecycle_areas(forms[path])
        if not found:
            continue
        if found != [(0, AREA_NAME, AREA)]:
            raise ValueError("Existing lifecycle area differs from the installer-owned area: " + str(path.relative_to(project)))
        if not all_forms:
            raise ValueError("Use --all-forms to migrate legacy list-row lifecycle areas before selecting individual forms")
        del forms[path]["pages"][0]["objects"][AREA_NAME]
        migrated.add(path)
        print("Removed legacy list-row lifecycle: " + str(path.relative_to(project)))

    def base(path, chain):
        if path in chain:
            raise ValueError("Inherited form cycle: " + str(path.relative_to(project)))
        if path in row_bases:
            raise ValueError("Lifecycle belongs in the list's detail parent, not its row form or shared row base: " + str(path.relative_to(project)))
        # Validate any local area before considering inherited ownership.
        checked = area_form(forms[path])
        inherited = parent(path)
        if inherited is None or inherited in row_bases:
            return path
        owner = base(inherited, [*chain, path])
        if checked == forms[path]:
            raise ValueError("Remove the installer-owned area from the derived form; its base owns lifecycle: " + str(path.relative_to(project)))
        return owner

    owners = set()
    for path in sorted(set(selected)):
        if all_forms and path in row_bases:
            print(("Skipped list-row form: " if path in row_forms else "Skipped shared list-row base: ") + str(path.relative_to(project)))
            continue
        if all_forms and forms[path].get("destination") not in (None, "", "detailScreen"):
            print("Skipped non-detail form: " + str(path.relative_to(project)))
            continue
        owners.add(base(path, []))
    # A selected derived form changes its shared base. Report every known
    # descendant, including unselected list/print forms, before any writes.
    parents = {}
    for path in paths:
        try:
            parents[path] = parent(path)
        except ValueError:
            continue  # Unrelated unresolved inheritance is not modified.
    for owner in sorted(owners):
        affected = []
        for path in paths:
            current, visited = path, set()
            while current in parents and current not in visited:
                visited.add(current)
                current = parents[current]
                if current == owner:
                    affected.append(str(path.relative_to(project)) + " [" + forms[path].get("destination", "unspecified") + "]")
                    break
        if affected:
            print("Shared lifecycle base: " + str(owner.relative_to(project)))
            for name in affected:
                print("  Inherited by: " + name)
    changes = {}
    for path in sorted(owners | migrated):
        original = originals[path]
        form = forms[path]
        updated = area_form(form) if path in owners else form
        if updated != json.loads(original):
            # Preserve the existing project's tab/space convention and its final newline, which
            # 4D omits: a form 4D saves again then differs only where the area was added.
            # All layout, events, methods and existing object values remain identical.
            indent = "\t" if re.search(r"\n\t+\S", original) else 2
            ending = "\n" if original.endswith("\n") else ""
            changes[path] = json.dumps(updated, ensure_ascii=False, indent=indent) + ending
    return changes


def main(argv=None, *, transform=None):
    """Install sources, optionally applying a trusted application's instrumentation."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project-dir", required=True, type=Path, help="Directory containing Sources/Methods")
    parser.add_argument("--compiler-method", default="Compiler_AXBHost", help="Compiler method to create or update")
    parser.add_argument("--area-list", action="store_true", help="Also install the AreaList grid and legacy row adapters")
    selection = parser.add_mutually_exclusive_group()
    selection.add_argument("--form", action="append", default=[], help="Add an area to a named form (repeatable); use TableForms/<table>/<form> for table forms")
    selection.add_argument("--all-forms", action="store_true", help="Add areas to detail forms, once per inheritance chain; skip list/print forms")
    parser.add_argument("--form-metadata", action="store_true", help="Refresh form metadata (list forms and objects' \"axb\" metadata) without adding lifecycle areas")
    parser.add_argument("--dry-run", action="store_true", help="Validate and list changes without writing")
    args = parser.parse_args(argv)
    args.project_dir = args.project_dir.resolve()
    methods = args.project_dir / "Sources/Methods"
    if not methods.is_dir():
        parser.error("--project-dir must already contain Sources/Methods")
    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", args.compiler_method):
        parser.error("--compiler-method must be a method name")
    sources = [p for p in sorted((ROOT / "host/OptionalMethods").glob("*.4dm")) if not p.stem.startswith("Compiler_")]
    if args.area_list:
        sources += [ROOT / "host/Methods" / (name + ".4dm") for name in sorted(AREA_METHODS)]
    expected_names = {p.name for p in sources}
    orphans = []
    for target in methods.glob("AXB_*.4dm"):
        if target.name not in expected_names and target.read_text().startswith(MARKER):
            orphans.append(target.name)
    if orphans:
        parser.error("Previously generated methods would be orphaned: " + ", ".join(sorted(orphans)) + ". Keep their install options or remove the methods and declarations deliberately.")
    changes = {}
    for path in sources:
        body = path.read_text()
        if transform is not None:
            body = transform(body, path.stem)
        target = methods / path.name
        if target.exists():
            old = target.read_text()
            header, _, old_body = old.partition("\n")
            if not header.startswith(MARKER) or header[len(MARKER):] != hashlib.sha256(old_body.encode()).hexdigest():
                parser.error(f"Refusing to replace a non-generated or edited method: {target}")
        changes[target] = MARKER + hashlib.sha256(body.encode()).hexdigest() + "\n" + body
    declarations = (ROOT / "host/OptionalMethods/Compiler_AXBHost.4dm").read_text().splitlines()
    if args.area_list:
        for line in (ROOT / "host/Methods/Compiler_AXB.4dm").read_text().splitlines():
            match = re.search(r"\((AXB_\w+);", line)
            if match and match[1] in AREA_METHODS:
                declarations.append(line)
    compiler = methods / (args.compiler_method + ".4dm")
    for other in methods.glob("*.4dm"):
        if other == compiler:
            continue
        content = other.read_text()
        if BEGIN in content or END in content:
            parser.error(f"Bridge declarations already exist in {other.stem}. Keep that compiler target or move its marked block deliberately before reinstalling.")
    old = compiler.read_text() if compiler.exists() else ""
    block = BEGIN + "\n" + "\n".join(declarations) + "\n" + END
    if BEGIN in old or END in old:
        if old.count(BEGIN) != 1 or old.count(END) != 1 or old.index(BEGIN) > old.index(END):
            parser.error("Compiler method has ambiguous bridge declaration markers")
        prefix, tail = old.split(BEGIN)
        _, suffix = tail.split(END)
        changes[compiler] = prefix + block + suffix
    else:
        changes[compiler] = old.rstrip() + "\n\n" + block + "\n"
    try:
        forms = form_changes(args.project_dir, args.form, args.all_forms)
        warnings = []
        metadata = form_metadata_changes(args.project_dir, bool(args.form or args.all_forms or args.form_metadata), warnings)
    except (ValueError, OSError, ET.ParseError) as failure:
        parser.error(str(failure))
    for warning in warnings:
        print("Warning: " + warning, file=sys.stderr)
    changes.update(forms)
    changes.update(metadata)
    if args.dry_run:
        for target, content in changes.items():
            if not target.exists() or target.read_text() != content:
                print(target.relative_to(args.project_dir) if target.is_relative_to(args.project_dir)
                      else "../" + str(target.relative_to(args.project_dir.parent)))
        return
    for target, content in changes.items():
        if not target.exists() or target.read_text() != content:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    print(f"Installed {len(sources)} host methods and declarations in {compiler}; updated {len(forms)} form definitions; no packages or data changed.")


if __name__ == "__main__":
    main()
